const {contextBridge,ipcRenderer}=require('electron');
const allowed=['update:status','update:progress','update:downloaded','auth:deep-link','workspace:realtime','drive:progress'];
contextBridge.exposeInMainWorld('qanteakDesktop',{
  getVersion:()=>ipcRenderer.invoke('app:version'),
  checkForUpdates:()=>ipcRenderer.invoke('update:check'),
  restartToUpdate:()=>ipcRenderer.invoke('update:install'),
  pickFiles:()=>ipcRenderer.invoke('files:pick'),
  saveFileCopy:(sourcePath,suggestedName)=>ipcRenderer.invoke('files:save-copy',sourcePath,suggestedName),
  saveInvoicePdf:(invoice)=>ipcRenderer.invoke('invoice:pdf',invoice),
  exportDiagnostics:()=>ipcRenderer.invoke('diagnostics:export'),
  reportRendererError:(payload)=>ipcRenderer.send('diagnostics:renderer-error',payload),
  getSecurityStatus:()=>ipcRenderer.invoke('security:status'),
  backendStatus:()=>ipcRenderer.invoke('backend:status'),
  backendSignIn:(email,password)=>ipcRenderer.invoke('backend:signin',email,password),
  backendSignUp:(payload)=>ipcRenderer.invoke('backend:signup',payload),
  backendRequestPasswordReset:(email)=>ipcRenderer.invoke('backend:password-reset-request',email),
  backendImportAuthUrl:(url)=>ipcRenderer.invoke('backend:auth-import-url',url),
  backendUpdatePassword:(password)=>ipcRenderer.invoke('backend:password-update',password),
  backendSignOut:()=>ipcRenderer.invoke('backend:signout'),
  backendEntitlement:()=>ipcRenderer.invoke('backend:entitlement'),
  backendWorkspaces:()=>ipcRenderer.invoke('backend:workspaces'),
  backendMembers:(workspaceId)=>ipcRenderer.invoke('backend:members',workspaceId),
  backendInvites:(workspaceId)=>ipcRenderer.invoke('backend:invites',workspaceId),
  backendInviteCreate:(payload)=>ipcRenderer.invoke('backend:invite-create',payload),
  backendInviteRevoke:(id)=>ipcRenderer.invoke('backend:invite-revoke',id),
  backendInviteAccept:(token)=>ipcRenderer.invoke('backend:invite-accept',token),
  backendPull:(workspaceId)=>ipcRenderer.invoke('backend:pull',workspaceId),
  backendPush:(workspaceId,snapshot,expectedRevision)=>ipcRenderer.invoke('backend:push',workspaceId,snapshot,expectedRevision),
  backendStartRealtime:(workspaceId)=>ipcRenderer.invoke('backend:realtime:start',workspaceId),
  backendStopRealtime:()=>ipcRenderer.invoke('backend:realtime:stop'),
  backendGetUserSettings:()=>ipcRenderer.invoke('backend:user-settings:get'),
  backendSaveUserSettings:(payload)=>ipcRenderer.invoke('backend:user-settings:set',payload),
  backendDriveStatus:(workspaceId)=>ipcRenderer.invoke('backend:drive-status',workspaceId),
  backendDriveList:(workspaceId)=>ipcRenderer.invoke('backend:drive-list',workspaceId),
  backendDriveUpload:(payload)=>ipcRenderer.invoke('backend:drive-upload',payload),
  backendDriveDownload:(fileId)=>ipcRenderer.invoke('backend:drive-download',fileId),
  backendDriveDelete:(payload)=>ipcRenderer.invoke('backend:drive-delete',payload),
  windowMinimize:()=>ipcRenderer.send('window:minimize'),
  windowToggleMaximize:()=>ipcRenderer.send('window:maximize-toggle'),
  windowClose:()=>ipcRenderer.send('window:close'),
  on:(channel,handler)=>{if(allowed.includes(channel))ipcRenderer.on(channel,(_e,payload)=>handler(payload))}
});
